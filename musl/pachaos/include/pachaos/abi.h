#define PACHAOS_PAGER_EVENT_FAULT 1u
#define PACHAOS_PAGER_EVENT_VMO_RELEASE 2u
/* A WAIT wake returns 2 with no event consumed; call PAGER_WAIT again. */
#define PACHAOS_PAGER_WAIT_RETRY_STATUS 2u
#define PACHAOS_PAGER_FAIL_IO 1u
#define PACHAOS_PAGER_FAIL_EOF_OR_TRUNCATE 2u
#define PACHAOS_PAGER_FAIL_PAGER_DEAD 3u
typedef struct pachaos_pager_event {
    uint32_t kind, flags;
    uint64_t key, vmo_generation, request_id, page_offset;
    uint32_t page_length, access;
} pachaos_pager_event_t;
typedef struct pachaos_pager_supply {
    uint64_t key, vmo_generation, request_id, source_fd;
    uint64_t source_offset, target_offset, length;
} pachaos_pager_supply_t;
_Static_assert(sizeof(pachaos_pager_event_t) == 48, "pager event ABI");
_Static_assert(sizeof(pachaos_pager_supply_t) == 56, "pager supply ABI");

