const TRAP_RUN_WASM: &[u8] = &[
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, // header
    0x01, 0x05, 0x01, 0x60, 0x00, 0x01, 0x7f, // type section
    0x03, 0x02, 0x01, 0x00, // function section
    0x07, 0x07, 0x01, 0x03, 0x72, 0x75, 0x6e, 0x00, 0x00, // export section
    0x0a, 0x05, 0x01, 0x03, 0x00, 0x00, 0x0b, // code section: unreachable
];

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = env::args().skip(1);
    let output = args
        .next()
        .ok_or("usage: wasmtime_artifact_builder <output-path> [minimal-run|minimal-run-wasm|hostcall-run|memory-log-run|memory-writeback-run|trap-run]")?;
    let variant = args
        .next()
        .unwrap_or_else(|| String::from(MINIMAL_RUN_VARIANT));
    let output_path = Path::new(&output);
    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)?;
    }

    let mut config = wasmtime::Config::new();
    wasmtime_config::configure_capabilityos_target(&mut config)?;
    let wasm = match variant.as_str() {
        MINIMAL_RUN_VARIANT => MINIMAL_RUN_WASM,
        MINIMAL_RUN_WASM_VARIANT => MINIMAL_RUN_WASM,
        HOSTCALL_RUN_VARIANT => HOSTCALL_RUN_WASM,
        MEMORY_LOG_RUN_VARIANT => MEMORY_LOG_RUN_WASM,
        MEMORY_WRITEBACK_RUN_VARIANT => MEMORY_WRITEBACK_RUN_WASM,
        TRAP_RUN_VARIANT => TRAP_RUN_WASM,
        _ => {
            return Err(format!(
                "unknown variant '{variant}', expected '{MINIMAL_RUN_VARIANT}', '{MINIMAL_RUN_WASM_VARIANT}', '{HOSTCALL_RUN_VARIANT}', '{MEMORY_LOG_RUN_VARIANT}', '{MEMORY_WRITEBACK_RUN_VARIANT}', or '{TRAP_RUN_VARIANT}'"
            )
            .into());
        }
    };
    if variant == MINIMAL_RUN_WASM_VARIANT {
        fs::write(output_path, wasm)?;
        println!(
            "generated raw wasm module: {} ({} bytes, variant={})",
            output_path.display(),
            wasm.len(),
            variant
        );
        return Ok(());
    }
    let engine = wasmtime::Engine::new(&config)?;
    let artifact = engine.precompile_module(wasm)?;
    fs::write(output_path, &artifact)?;
    println!(
        "generated serialized module: {} ({} bytes, variant={})",
        output_path.display(),
        artifact.len(),
        variant
    );
    Ok(())
}
