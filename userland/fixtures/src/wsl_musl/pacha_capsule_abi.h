static inline int pacha_capsule_is_syscall(uint64_t nr) {
    return nr >= PACHA_SYSCALL_CAPSULE_FIRST && nr <= PACHA_SYSCALL_CAPSULE_LAST;
}

static inline uint64_t pacha_capsule_token_kind(uint64_t token) {
    return (token >> 48) & UINT64_C(0x0F);
}

static inline int pacha_capsule_token_has_kind(uint64_t token, uint64_t kind) {
    return ((token >> 56) == PACHA_CAPSULE_TOKEN_MAGIC) &&
        (((token >> 52) & UINT64_C(0x0F)) == PACHA_CAPSULE_TOKEN_VERSION) &&
        (pacha_capsule_token_kind(token) == kind);
}

